#!/usr/bin/env python3
"""Build assets/spa-sample.js for learn-sales-pipeline-analytics-with-phoebe.

Internal build script. Never linked from an audience page.

Usage:  python3 materials/build-spa-sample.py [<dir-with-csvs>]
With no directory it downloads the public dataset with no login:
  kagglehub.dataset_download("olistbr/marketing-funnel-olist")
  (Marketing Funnel by Olist, CC BY-NC-SA 4.0. 8,000 MQLs first contacted 2017-06-14 to
   2018-05-31; 842 closed deals won 2017-12-05 to 2018-11-14.)

REAL (shipped for all 8,000 rows): origin, first-contact day, won day (or -1).
  Days count from 2018-01-01 (2017 rows are negative). One won row has won_date 2 days before
  first contact; its cycle is clipped to 0 (a3 teaches it as a logging defect).
CONSTRUCTED (seeded, labelled on every widget), only for rows in one of two open pools:
  prior pool    leads first contacted 2018-01-01..02-28 and not won before 2018-03-01 (day 59)
  current pool  leads first contacted 2018-03-01..05-31 and not won before 2018-06-01 (day 151)
  per row: stage 1-5 as of its pool's as-of date, amount (units of 10,000 yen), rep 0-3,
  happy flag (the row a rep would inflate by one stage).
  Stage rule (the rep's honest read, built from the row's REAL outcome so stages carry signal):
    real win inside the next 91 days: days-to-win <30 -> 5, <60 -> 4, else 3; then 25% drop one step
    real win after that window: 2 or 3 (even)
    never won: 1 (55%), 2 (25%), 3 (12%), 4 (6%), 5 (2%)
  Amount: lognormal, median 360,000 yen, sigma 0.9, floor 60,000, rounded to 10,000.
  Draws: 20 seeded samples of 300 rows from the current pool = 20 replays of the quarter;
  draw 0 is "this quarter".
"""
import json, os, sys
import numpy as np
import pandas as pd

SEED = 20181011
ORIGINS = ["organic_search", "paid_search", "social", "email", "referral", "display",
           "unknown", "direct_traffic", "other", "other_publicities", "(blank)"]
DAY0 = pd.Timestamp("2018-01-01")
PRIOR_ASOF, ASOF, Q = 59, 151, 91
N_DRAWS, DRAW_N = 20, 300

def load(d):
    m = pd.read_csv(os.path.join(d, "olist_marketing_qualified_leads_dataset.csv"))
    c = pd.read_csv(os.path.join(d, "olist_closed_deals_dataset.csv"))
    x = m.merge(c[["mql_id", "won_date"]], on="mql_id", how="left")
    x["origin"] = x["origin"].fillna("(blank)")
    x["fc"] = (pd.to_datetime(x.first_contact_date) - DAY0).dt.days
    wd = pd.to_datetime(x.won_date).dt.normalize()
    x["wd"] = ((wd - DAY0).dt.days).fillna(-9999).astype(int)
    x = x.sort_values(["fc", "mql_id"]).reset_index(drop=True)
    return x, len(m), len(c)

def main():
    d = sys.argv[1] if len(sys.argv) > 1 else None
    if not d:
        import kagglehub
        d = kagglehub.dataset_download("olistbr/marketing-funnel-olist")
    x, nm, nc = load(d)
    rng = np.random.default_rng(SEED)
    n = len(x)
    o = [ORIGINS.index(v) for v in x.origin]
    c = [int(v) for v in x.fc]
    w = [(-1 if v == -9999 else max(int(v), int(f))) for v, f in zip(x.wd, x.fc)]
    neg = int(((x.wd != -9999) & (x.wd < x.fc)).sum())
    st = [0] * n; amt = [0] * n; rep = [0] * n; hp = [0] * n
    for i in range(n):
        if 0 <= c[i] < 59 and not (w[i] != -1 and w[i] < PRIOR_ASOF): asof = PRIOR_ASOF
        elif 59 <= c[i] < 151 and not (w[i] != -1 and w[i] < ASOF): asof = ASOF
        else: continue
        u = rng.random(4)
        if w[i] != -1 and w[i] < asof + Q:
            dtw = w[i] - asof
            s = 5 if dtw < 30 else 4 if dtw < 60 else 3
            if u[0] < 0.25: s -= 1
        elif w[i] != -1:
            s = 2 if u[0] < 0.5 else 3
        else:
            s = 1 if u[0] < .55 else 2 if u[0] < .80 else 3 if u[0] < .92 else 4 if u[0] < .98 else 5
        st[i] = s
        a = np.exp(np.log(36) + 0.9 * rng.standard_normal())
        amt[i] = max(6, int(round(a)))
        rep[i] = int(u[1] * 4)
        hp[i] = 1 if (s < 5 and u[2] < 0.30) else 0
    pool = [i for i in range(n) if 59 <= c[i] < 151 and st[i] > 0]
    draws = [sorted(rng.choice(pool, DRAW_N, replace=False).tolist()) for _ in range(N_DRAWS)]
    S = {"origins": ORIGINS, "asOf": ASOF, "priorAsOf": PRIOR_ASOF, "q": Q, "day0": "2018-01-01",
         "rows": {"o": o, "c": c, "w": w, "st": st, "amt": amt, "rep": rep, "hp": hp},
         "draws": draws,
         "reps": [{"name": "Aiko", "commitAt": 5}, {"name": "Ben", "commitAt": 4},
                  {"name": "Chiara", "commitAt": 5}, {"name": "Dev", "commitAt": 6}],
         "stages": ["Contacted", "Need confirmed", "Tasting trial", "Proposal", "Contract out"],
         "hubspotDefault": [0.2, 0.4, 0.6, 0.8, 0.9],
         "meta": {"mqls": nm, "closed": nc, "negCycle": neg, "seed": SEED, "pool": len(pool)}}
    js = ("/* spa-sample.js - generated by materials/build-spa-sample.py; do not edit.\n"
          " * Real: Olist marketing funnel rows (origin, first contact, won date). Constructed: stage,\n"
          " * amount, rep, happy flag, draws (seeded). */\n"
          "window.SPA_SAMPLE = " + json.dumps(S, separators=(",", ":")) + ";\n")
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "assets", "spa-sample.js")
    open(out, "w").write(js)
    print("rows", n, "mqls", nm, "closed", nc, "neg", neg, "pool", len(pool), "bytes", len(js))

if __name__ == "__main__":
    main()
